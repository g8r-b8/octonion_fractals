order = []
glyphs = {}
cur_name = None
cur_rows = []

def commit():
    if cur_name is not None:
        glyphs[cur_name] = tuple(cur_rows)
        order.append(cur_name)

for line in RAW.strip().splitlines():
    line = line.rstrip()
    if line.endswith(':'):
        commit()
        cur_name = line[:-1]
        cur_rows = []
    elif line:
        bits = 0
        for i, ch in enumerate(line):
            if ch == 'X':
                bits |= (1 << (2 - i))
        cur_rows.append(bits)
commit()

name_for_char = {
    ' ': 'SPACE',
    '.': 'DOT',
    ',': 'COMMA',
    ':': 'COLON',
    '/': 'SLASH',
    '(': 'LPAREN',
    ')': 'RPAREN',
    '-': 'DASH',
    '+': 'PLUS',
}

def encode(name):
    r = glyphs[name]
    v = 0
    for i, row in enumerate(r):
        v |= row << (i * 3)
    return v

def char_to_id(ch):
    if 'A' <= ch <= 'Z':
        return order.index(ch)
    if '0' <= ch <= '9':
        return order.index(ch)
    n = name_for_char.get(ch)
    if n is None:
        raise ValueError(f"no glyph for {ch!r}")
    return order.index(n)

